create database e_commerce_sales_project;

create table customers(
  customer_id	varchar(50),
  customer_name	varchar(50),
  gender	varchar(50),
  age numeric(10),
  city varchar(50),
  state varchar(50),
  signup_date date
);

select* from customers

create table orders_item(
      order_item_id varchar(50),	
	  order_id varchar(50),
	  product_id	varchar(50),
	  quantity numeric(10),
	  unit_price numeric(10),
	  discount_pct numeric(10),
	  gross_amount numeric(20),
	  discount_amount numeric(20),
	  net_sales numeric(10),
	  unit_cost numeric(10),
	  total_cost	numeric(10),
	  profit numeric(10)
);

select* from orders_item;

create table orders(
 order_id varchar(20),
 order_date date,
 customer_id varchar(20),
 order_status varchar(20),
 payment_method	varchar(10),
 shipping_fee numeric(10)
);

select* from orders


create table payments(
       payment_id varchar(20),
	   order_id varchar(20),
	   payment_method	varchar(20),
	   payment_status varchar(20),
	   amount	numeric(20),
	   payment_date date
);

select* from payments

create table product(
   product_id  varchar(20),
   product_name	varchar(20),
   category	varchar(10),
   subcategory varchar(20),
   unit_price	numeric(20),
   unit_cost numeric(10)
);

select* from product

create table shipment(
    shipment_id varchar(10),
	order_id varchar(10),
	carrier varchar(10),
	warehouse_city	varchar(10),
	shipping_days numeric(10),
	delivery_status varchar(10)
);

select* from shipment

--E-commerce Business & Sales Analysis Using SQL

--Sales Performance Analysis

--What is the total revenue generated?

select sum(amount) from payments

--What is the total number of orders?

select  count (distinct order_id) from orders_item

--What is the total quantity of products sold?

select sum(quantity) from orders_item

--What is the average order value (AOV)?

select sum(amount) /  count (distinct order_id) as average_order_value from payments

--What is the total profit generated?

select sum(profit) from orders_item

--What is the overall profit margin?

select sum(o.profit)/ sum (p.amount) * 100 as profit_margin  from orders_item o join payments p on o.order_id=p.order_id

--Which month generated the highest revenue?

select date_part('month', payment_date) as month, sum(amount) as total_revenue from payments group by date_part('month', payment_date),amount  order by amount desc limit 1 

--Which are the top 10 profit-generating products?

select sum(o.profit) as profit, p.product_name from orders_item o join product p on o.product_id=p.product_id group by p.product_name order by profit desc limit 10;

--Which category has the highest profit margin?

select pr.category, sum(p.amount)/sum(o.profit) * 100 as profit_margin from orders_item o join payments p on o.order_id = p.order_id join product pr on pr.product_id = o.product_id group by pr.category order by profit_margin desc limit 10

--Which city have placed the highest number of orders?

select distinct(count(o.order_id)) as No_of_order , c.city from orders o  join customers c on o.customer_id=c.customer_id group by c.city order by No_of_order desc limit 5

--Which city has the highest number of customers?

select distinct(count(customer_id)) as customer_number, city from customers group by city order by customer_number desc

--Which customers have made repeat purchases?

select distinct(c.customer_name) as customers, count(distinct(o.order_id)) as no_of_buy from customers c join orders o on o.customer_id=c.customer_id group by customers order by  no_of_buy desc

--how much amount of payments are refunded?

select  sum(amount) as refunded_amount from payments where payment_status = 'Refunded'


--What is the total revenue generated by each payment method?

  select payment_method, sum(amount) as amount from payments group by payment_method order by amount desc

--What is the distribution of orders by order status?

select order_status, count(distinct(order_id)) as no_of_orders from orders group by order_status order by no_of_orders desc  

--What is the cancellation rate?

SELECT
    COUNT(*) FILTER (WHERE order_status = 'Cancelled') AS cancelled_orders,
    COUNT(*) AS total_orders,
    ROUND(
        COUNT(*) FILTER (WHERE order_status = 'Cancelled') * 100.0
        / COUNT(*), 2
    ) AS cancellation_rate
FROM orders;

--Which shipping company has the highest number of delayed deliveries?

 select distinct(carrier) as delivery_company , 
 sum( case when delivery_status='Delayed' then 1 else 0 end ) as delayed_no 
 from shipment
 group by delivery_company
 order by delayed_no desc

--What percentage of shipments are delayed?

select sum(case when delivery_status='Delayed' then 1 else 0 end ) * 100 / count(delivery_status) as delayed_percentage from shipment
 
--Rank the top 5 products in each category based on profit.

select p.product_name, sum(o.profit), p.category,
rank() over(partition by p.category order by sum(o.profit) desc) as product_rank from product p join orders_item o on p.product_id=o.product_id group by p.product_name, p.category



